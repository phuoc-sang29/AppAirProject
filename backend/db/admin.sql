create table if not exists users (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  health_group text default 'binh_thuong',
  role text default 'user',
  fcm_token text,
  created_at timestamptz default now()
);
alter table users add column if not exists role text default 'user';
alter table users add column if not exists is_blocked boolean default false;

create table if not exists ratings (
  id uuid default gen_random_uuid() primary key,
  user_id uuid references auth.users(id) on delete cascade,
  stars int check (stars between 1 and 5),
  feedback text,
  created_at timestamptz default now()
);

create table if not exists map_searches (
  id serial primary key,
  user_id text,
  address text,
  lat float,
  lon float,
  pm25 float,
  searched_at timestamptz default now()
);

create table if not exists notifications (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  message text not null,
  level text not null default 'info',
  is_read boolean default false,
  created_at timestamptz default now()
);

create table if not exists news_articles (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'Cảnh báo hôm nay',
  summary text not null,
  content text not null,
  author text default 'Ban biên tập AppAir',
  is_published boolean default true,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

insert into users (id, email, full_name, health_group)
select id, email,
  raw_user_meta_data->>'full_name',
  coalesce(raw_user_meta_data->>'health_group', 'binh_thuong')
from auth.users
on conflict (id) do nothing;

create or replace function is_admin() returns boolean
language sql security definer set search_path = public stable
as $$
  select exists (select 1 from users where id = auth.uid() and role = 'admin')
$$;

create or replace function guard_user() returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  if auth.uid() is not null and not is_admin() then
    if new.role is distinct from old.role
       or new.is_blocked is distinct from old.is_blocked then
      raise exception 'Khong duoc phep doi quyen hoac trang thai tai khoan';
    end if;
  end if;
  return new;
end
$$;

drop trigger if exists guard_user_trg on users;
create trigger guard_user_trg before update on users
for each row execute function guard_user();

alter table users enable row level security;
drop policy if exists "User read own" on users;
drop policy if exists "User update own" on users;
drop policy if exists "User insert own" on users;
drop policy if exists users_select on users;
drop policy if exists users_insert on users;
drop policy if exists users_update on users;
create policy users_select on users for select
  using (id = auth.uid() or is_admin());
create policy users_insert on users for insert
  with check (id = auth.uid() and coalesce(role, 'user') = 'user');
create policy users_update on users for update
  using (id = auth.uid() or is_admin());

alter table ratings enable row level security;
drop policy if exists "User insert rating" on ratings;
drop policy if exists "Read all ratings" on ratings;
drop policy if exists ratings_insert on ratings;
drop policy if exists ratings_select on ratings;
create policy ratings_insert on ratings for insert
  with check (auth.uid() is not null);
create policy ratings_select on ratings for select
  using (is_admin());

